//! The finding table and the generated findings reference.
//!
//! `stetdoc_core::api::check` lists every finding code once, in a `finding_codes!` invocation of literals: the variant, the wire
//! name, the class and a sentence. Like the error codes and the operations, it is read from source with `syn`, never linked, so a
//! core that does not build still gets every static check. The reference `docs/reference/findings.md` is written from it by
//! `cargo xtask docs`, and the generated-docs drift check fails when it is stale.

use crate::violation::Violation;
use syn::parse::{ParseStream, Parser};
use syn::{Item, LitStr, Token};

/// The file the table lives in.
pub const SPEC_FILE: &str = "crates/stetdoc-core/src/api/check.rs";

/// The generated reference.
pub const REFERENCE: &str = "docs/reference/findings.md";

/// One finding code.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Finding {
    /// The `FindingCode` variant.
    pub variant: String,
    /// The name on the wire.
    pub wire: String,
    /// `Violation` or `Note`.
    pub class: String,
    /// What the code means.
    pub doc: String,
}

fn fail(line: usize, message: impl Into<String>) -> Violation {
    Violation::new(
        SPEC_FILE,
        line,
        message,
        "keep the shape the docs read: one `finding_codes!` invocation of `Variant { wire, class, doc }` entries, written with literals",
    )
}

/// Parses the text of `api/check.rs`.
pub fn parse(source: &str) -> Result<Vec<Finding>, Violation> {
    let file = syn::parse_file(source).map_err(|e| {
        fail(
            e.span().start().line,
            format!("cannot parse this file: {e}"),
        )
    })?;
    for item in &file.items {
        if let Item::Macro(m) = item
            && m.mac.path.is_ident("finding_codes")
        {
            return entries.parse2(m.mac.tokens.clone()).map_err(|e| {
                fail(
                    e.span().start().line,
                    format!("cannot read the finding_codes! table: {e}"),
                )
            });
        }
    }
    Err(fail(0, "there is no `finding_codes!` invocation"))
}

fn entries(input: ParseStream) -> syn::Result<Vec<Finding>> {
    let mut out = Vec::new();
    while !input.is_empty() {
        let variant: syn::Ident = input.parse()?;
        let body;
        syn::braced!(body in input);
        let mut finding = Finding {
            variant: variant.to_string(),
            wire: String::new(),
            class: String::new(),
            doc: String::new(),
        };
        while !body.is_empty() {
            let key: syn::Ident = body.parse()?;
            body.parse::<Token![:]>()?;
            match key.to_string().as_str() {
                "wire" => finding.wire = body.parse::<LitStr>()?.value(),
                "class" => finding.class = body.parse::<syn::Ident>()?.to_string(),
                "doc" => finding.doc = body.parse::<LitStr>()?.value(),
                other => {
                    return Err(syn::Error::new(
                        key.span(),
                        format!("unknown key `{other}`"),
                    ));
                }
            }
            if body.peek(Token![,]) {
                body.parse::<Token![,]>()?;
            }
        }
        out.push(finding);
    }
    Ok(out)
}

/// Writes the reference.
pub fn render(findings: &[Finding]) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "<!-- Generated by `cargo xtask docs` from `{SPEC_FILE}`. Do not edit by hand. -->\n\n"
    ));
    out.push_str("# Findings reference\n\n");
    out.push_str(&format!(
        "`stetdoc check` and the receipt of an edit report findings. There are {} codes. A **violation** is a departure from the schema or from a Word rule, which an edit may not add: an edit that would add one is refused as `validation_failed`, and a violation that the document already had is reported and not blamed on the edit. A **note** is legal and worth saying. A code is stable once released: new codes may be added, and existing ones are never repurposed or removed outside a major version.\n\n",
        findings.len()
    ));
    for (class, title) in [("Violation", "Violations"), ("Note", "Notes")] {
        let of_class: Vec<&Finding> = findings.iter().filter(|f| f.class == class).collect();
        out.push_str(&format!(
            "## {title}\n\n| Code | What it means |\n|---|---|\n"
        ));
        for f in of_class {
            out.push_str(&format!(
                "| `{}` | {} |\n",
                f.wire,
                f.doc.replace('|', "\\|")
            ));
        }
        out.push('\n');
    }
    out.trim_end().to_string() + "\n"
}

#[cfg(test)]
pub mod tests {
    use super::*;
    use crate::repo::Repo;

    /// The real table, read from the repository.
    pub fn real() -> Vec<Finding> {
        let source = Repo::discover()
            .and_then(|r| r.read(SPEC_FILE))
            .expect("read");
        parse(&source).expect("parse")
    }

    #[test]
    fn the_real_table_reads_and_is_whole() {
        let findings = real();
        assert!(findings.len() > 40);
        let mut wires: Vec<&str> = findings.iter().map(|f| f.wire.as_str()).collect();
        wires.sort_unstable();
        wires.dedup();
        assert_eq!(wires.len(), findings.len(), "a wire name is used twice");
        for f in &findings {
            assert!(!f.wire.is_empty() && !f.doc.is_empty(), "{}", f.variant);
            assert!(
                matches!(f.class.as_str(), "Violation" | "Note"),
                "{}",
                f.variant
            );
        }
        let out_of_order = findings
            .iter()
            .find(|f| f.wire == "schema_out_of_order")
            .expect("a schema code");
        assert_eq!(out_of_order.class, "Violation");
    }

    #[test]
    fn the_reference_lists_every_code_under_its_class() {
        let findings = real();
        let doc = render(&findings);
        for f in &findings {
            assert!(doc.contains(&format!("| `{}` |", f.wire)), "{}", f.wire);
        }
        let notes = doc.split("## Notes").nth(1).expect("a notes section");
        assert!(notes.contains("`unanchored`") && !notes.contains("`schema_out_of_order`"));
        assert!(doc.ends_with("|\n"), "one newline at the end");
    }

    #[test]
    fn a_table_that_cannot_be_read_is_reported_not_a_panic() {
        assert!(parse("fn broken( {").is_err());
        assert!(parse("fn fine() {}").is_err());
        assert!(parse("finding_codes! { A { colour: \"red\" } }").is_err());
    }
}
