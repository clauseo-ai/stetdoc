//! The file-size check.
//!
//! A source file over 600 lines fails unless the exceptions file lists it with a
//! reason. Files under a `generated/` directory are excluded. An exception for a file
//! that no longer needs one is also a failure, so the list cannot rot.

use crate::exceptions;
use crate::repo::{Repo, Res};
use crate::violation::Violation;

/// The longest a file may be without an exception.
pub const MAX_LINES: usize = 600;

/// The exceptions file, relative to the repository root.
pub const EXCEPTIONS: &str = "xtask/file-size-exceptions.txt";

/// Extensions of the files the check measures.
const EXTENSIONS: &[&str] = &["rs", "ts", "tsx", "js", "mjs"];

/// Runs the check against the repository.
pub fn check(repo: &Repo) -> Res<Vec<Violation>> {
    let exceptions = if repo.exists(EXCEPTIONS) {
        repo.read(EXCEPTIONS)?
    } else {
        String::new()
    };
    let mut sizes = Vec::new();
    for file in repo.files()? {
        if is_measured(&file) {
            let text = repo.read(&file)?;
            sizes.push((file, text.lines().count()));
        }
    }
    Ok(check_sizes(&sizes, &exceptions))
}

fn is_measured(path: &str) -> bool {
    let generated = path.split('/').any(|part| part == "generated");
    let extension = path.rsplit_once('.').map(|(_, e)| e).unwrap_or("");
    !generated && EXTENSIONS.contains(&extension)
}

/// Checks `(path, line count)` pairs against the exceptions text.
pub fn check_sizes(sizes: &[(String, usize)], exceptions: &str) -> Vec<Violation> {
    let (listed, mut problems) =
        exceptions::parse(EXCEPTIONS, "why this file may stay large", exceptions);
    for (path, lines) in sizes {
        let over = *lines > MAX_LINES;
        match listed.get(path) {
            None if over => problems.push(Violation::new(
                path,
                MAX_LINES + 1,
                format!("this file has {lines} lines, over the limit of {MAX_LINES}"),
                format!(
                    "split it along a concept into smaller files, or list it in {EXCEPTIONS} as `{path} | reason`"
                ),
            )),
            Some(exception) if !over => problems.push(Violation::new(
                EXCEPTIONS,
                exception.line,
                format!(
                    "`{path}` has {lines} lines, within the limit, but is listed as an exception ({})",
                    exception.reason
                ),
                "remove the entry",
            )),
            _ => {}
        }
    }
    for (path, exception) in &listed {
        if !sizes.iter().any(|(p, _)| p == path) {
            problems.push(Violation::new(
                EXCEPTIONS,
                exception.line,
                format!("`{path}` is listed as an exception but is not a measured source file"),
                "remove the entry, or correct the path",
            ));
        }
    }
    problems
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::repo::testutil::repo;

    fn sized(path: &str, lines: usize) -> (String, usize) {
        (path.to_string(), lines)
    }

    #[test]
    fn exactly_the_limit_passes_and_one_over_fails_at_the_first_excess_line() {
        assert_eq!(check_sizes(&[sized("a.rs", 600)], ""), []);
        let found = check_sizes(&[sized("a.rs", 601)], "");
        assert_eq!(found.len(), 1);
        assert_eq!(found[0].file, "a.rs");
        assert_eq!(found[0].line, 601);
        assert!(found[0].fix.contains(EXCEPTIONS));
    }

    #[test]
    fn a_listed_exception_with_a_reason_passes() {
        let ex = "# comment\n\na.rs | generated by hand from a spec table\n";
        assert_eq!(check_sizes(&[sized("a.rs", 900)], ex), []);
    }

    #[test]
    fn an_exception_without_a_reason_fails() {
        let found = check_sizes(&[sized("a.rs", 900)], "a.rs\n");
        assert!(
            found.iter().any(|v| v.file == EXCEPTIONS && v.line == 1),
            "{found:?}"
        );
        assert!(
            found.iter().any(|v| v.file == "a.rs"),
            "the file itself is still over: {found:?}"
        );
    }

    #[test]
    fn a_stale_exception_fails() {
        let small = check_sizes(&[sized("a.rs", 10)], "a.rs | was big once\n");
        assert_eq!(small.len(), 1);
        assert!(small[0].message.contains("within the limit"));
        let gone = check_sizes(&[], "gone.rs | was big once\n");
        assert_eq!(gone.len(), 1);
        assert!(gone[0].message.contains("not a measured source file"));
    }

    #[test]
    fn generated_directories_and_other_extensions_are_not_measured() {
        let (_dir, repo) = repo(&[
            ("crates/a/src/generated/table.rs", &"x\n".repeat(900)),
            ("docs/long.md", &"x\n".repeat(900)),
            ("crates/a/src/lib.rs", "fn main() {}\n"),
        ]);
        assert_eq!(check(&repo).expect("runs"), []);
    }

    #[test]
    fn check_finds_a_long_file_in_a_repository() {
        let (_dir, repo) = repo(&[("crates/a/src/big.rs", &"x\n".repeat(601))]);
        let found = check(&repo).expect("runs");
        assert_eq!(found.len(), 1);
        assert_eq!(found[0].file, "crates/a/src/big.rs");
    }
}
